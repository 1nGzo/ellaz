// Trusted Chrome touch input plus Safari-event contract checks; not an iPad test.
// Uses an existing Playwright/browser installation, no downloads.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { extname, join } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH });
try {
 const context = await browser.newContext({ viewport: { width: 820, height: 1180 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' });
 const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.woff2': 'font/woff2' };
 await context.route('**/*', async route => {
  const url = new URL(route.request().url());
  if (url.hostname !== 'ellaz.test') return route.abort();
  let file = join(process.argv[2] ?? 'dist', decodeURI(url.pathname));
  if (!extname(file)) file = join(file, 'index.html');
  try { await route.fulfill({ contentType: types[extname(file)] ?? 'application/octet-stream', body: await readFile(file) }); }
  catch { await route.fulfill({ status: 404, body: '' }); }
 });
 const page = await context.newPage();
 const errors = [];
 page.on('pageerror', e => errors.push(e.message));
 const cdp = await context.newCDPSession(page);
 const touch = (type, points) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: points.map(([x,y], id) => ({ x,y,id })) });
 for (const path of ['/', '/games/memory/?play=preschool']) {
  await page.goto('https://ellaz.test' + path);
  await page.locator(path === '/' ? '#root button' : '.ellaz-play-surface button').first().waitFor();
  // A nested scroller also exercises the ancestor boundary of touch-action.
  await page.evaluate(() => {
   const scroller = document.createElement('div'); scroller.id = 'zoom-probe';
   scroller.style.cssText = 'position:fixed;inset:100px 20px auto;height:400px;overflow:auto;z-index:99999;background:white';
   scroller.innerHTML = '<div style="height:2000px">Touch probe</div>';
   document.body.append(scroller);
   window.__pointers = 0;
   scroller.addEventListener('pointerdown', () => window.__pointers++);
  });
  const scale = await page.evaluate(() => visualViewport.scale);
  await touch('touchStart', [[300,250],[400,250]]);
  for (let n=1;n<=8;n++) await touch('touchMove', [[300-n*20,250],[400+n*20,250]]);
  await touch('touchEnd', []);
  assert.equal(await page.evaluate(() => visualViewport.scale), scale, 'pinch must not change viewport scale');
  await touch('touchStart', [[250,420]]);
  for (let n=1;n<=8;n++) await touch('touchMove', [[250,420-n*30]]);
  await touch('touchEnd', []);
  assert(await page.locator('#zoom-probe').evaluate(el => el.scrollTop) > 0, 'single-finger scrolling');
  await page.touchscreen.tap(250,250); await page.touchscreen.tap(250,250);
  assert.equal(await page.evaluate(() => visualViewport.scale), scale, 'double tap must not zoom');
  assert(await page.evaluate(() => window.__pointers) >= 4, 'pointerdown remains delivered');
  // Safari's proprietary event cannot be generated by Chrome's input backend.
  assert(await page.evaluate(() => {
   const e = new Event('gesturestart', { bubbles:true, cancelable:true });
   document.querySelector('#zoom-probe').dispatchEvent(e); return e.defaultPrevented;
  }));
  // A game-owned drag surface retains capture and receives real touch moves.
  await page.locator('#zoom-probe').evaluate(el => {
   el.style.touchAction = 'none'; window.__drag = 0;
   el.addEventListener('pointerdown', e => el.setPointerCapture(e.pointerId));
   el.addEventListener('pointermove', () => window.__drag++);
  });
  await touch('touchStart', [[250,250]]);
  await touch('touchMove', [[350,300]]); await touch('touchMove', [[400,350]]);
  await touch('touchEnd', []);
  assert(await page.evaluate(() => window.__drag) >= 2, 'captured pointer drag');
  await page.locator('#zoom-probe').evaluate(el => el.remove());
  if (path !== '/') {
   const card = page.locator('.ellaz-play-surface button').first();
   await card.tap(); assert.notEqual(await card.textContent(), '❓', 'normal game tap');
  }
  console.log('PASS touch pinch, double tap, scroll, pointer capture, Safari guard:', path);
 }
 assert.deepEqual(errors, []);
} finally { await browser.close(); }
